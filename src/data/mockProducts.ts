function generatePriceHistory(
  basePrice: number,
  months: number,
  volatility: number
): { timestamp: string; price: number }[] {
  const history: { timestamp: string; price: number }[] = [];
  const now = new Date();
  for (let i = months * 30; i >= 0; i -= 3) {
    const date = new Date(now);
    date.setDate(date.getDate() - i);
    const noise = (Math.random() - 0.5) * 2 * volatility * basePrice;
    const seasonal = Math.sin((date.getMonth() / 12) * Math.PI * 2) * basePrice * 0.05;
    const price = Math.max(basePrice * 0.7, basePrice + noise + seasonal);
    history.push({
      timestamp: date.toISOString().split('T')[0],
      price: Math.round(price * 100) / 100,
    });
  }
  return history;
}

